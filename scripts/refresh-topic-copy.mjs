const source = readFileSync(appPath, "utf8");
const block = source.match(/const questionBank = (\{[\s\S]*?\n  \});\r?\n\r?\n  const state =/);
if (!block) throw new Error("Could not locate questionBank in site/app.js");
const bank = new Function(`return (${block[1]});`)();

for (const [label, questions] of Object.entries(updates)) {
  if (!topicKeyByLabel[label] || !Array.isArray(bank[label]) || bank[label].length !== 15) {
    throw new Error(`Unexpected question bank topic: ${label}`);
  }
  if (questions.length !== 15) throw new Error(`${label} must contain fifteen updates`);
  bank[label] = questions.map(([prompt, choiceA, choiceB], index) => ({
    prompt,
    choices: [choiceA, choiceB],
    demoAnswer: bank[label][index].demoAnswer,
  }));
}

const escapeRegExp = (value) => value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
let updatedApp = source;
for (const [label, questions] of Object.entries(updates)) {
  const key = /^[$_\p{ID_Start}][$\u200C\u200D_\p{ID_Continue}]*$/u.test(label)
    ? label
    : JSON.stringify(label);
  const topicPattern = new RegExp(
    `(^    ${escapeRegExp(key)}: \\[)[\\s\\S]*?^    \\]`,
    "m",
  );
  const entries = questions.map(([prompt, choiceA, choiceB], index) => {
    const demoAnswer = bank[label][index].demoAnswer;
    return `      { prompt: ${JSON.stringify(prompt)}, choices: [${JSON.stringify(choiceA)}, ${JSON.stringify(choiceB)}], demoAnswer: ${demoAnswer} },`;
  }).join("\n");
  const replacement = `    ${key}: [\n${entries}\n    ]`;
  if (!topicPattern.test(updatedApp)) {
    throw new Error(`Could not locate question array for ${label}`);
  }
  updatedApp = updatedApp.replace(topicPattern, replacement);
}
writeFileSync(appPath, updatedApp);

const escapeSql = (value) => value.replaceAll("'", "''");
const rows = [];
for (const [label, topicKey] of Object.entries(topicKeyByLabel)) {
  for (const [index, question] of bank[label].entries()) {
    rows.push(
      `  ('${topicKey}', ${index + 1}, '${escapeSql(question.prompt)}', '${escapeSql(question.choices[0])}', '${escapeSql(question.choices[1])}')`,
    );
  }
}
const migration = `-- Refresh non-K-pop topics with specific, everyday situations.\ninsert into public.question_bank (topic_key, question_no, prompt, choice_a, choice_b)\nvalues\n${rows.join(",\n")}\non conflict (topic_key, question_no) do update\nset prompt = excluded.prompt,\n    choice_a = excluded.choice_a,\n    choice_b = excluded.choice_b;\n`;
writeFileSync(migrationPath, migration);
console.log(`Updated ${Object.keys(updates).length} topics and wrote ${rows.length} database rows.`);
